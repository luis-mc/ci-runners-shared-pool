/**
 * Builds the token values of each theme from `themes.data.ts` and writes them as CSS (design system tokens.md,
 * Colour themes). Pure functions; `gen-themes.ts` writes the file, `themes.test.ts` proves it is current.
 */
import {
  DEFAULT_THEME,
  TERMINAL,
  TERMINAL_LIGHT,
  THEME_DATA,
  type Palette,
  type ThemeData,
} from './themes.data.ts';

type Rgb = readonly [number, number, number];
const toRgb = (h: string): Rgb => [
  parseInt(h.slice(1, 3), 16),
  parseInt(h.slice(3, 5), 16),
  parseInt(h.slice(5, 7), 16),
];
const toHex = (c: Rgb): string =>
  '#' + c.map((n) => Math.round(n).toString(16).padStart(2, '0')).join('');
/** `t` of `b` over `a`. */
export function mix(a: string, b: string, t: number): string {
  const [x, y] = [toRgb(a), toRgb(b)];
  return toHex(
    [0, 1, 2].map(
      (i) => (x[i] as number) * (1 - t) + (y[i] as number) * t,
    ) as unknown as Rgb,
  );
}
function lum(h: string): number {
  const lin = (c: number): number => {
    const s = c / 255;
    return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
  };
  const [r, g, b] = toRgb(h);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}
export function ratio(a: string, b: string): number {
  const [hi, lo] = [lum(a), lum(b)].sort((p, q) => q - p) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

const TONES = [
  ['done', 'done'],
  ['note', 'note'],
  ['needs-you', 'needs'],
  ['problem', 'problem'],
] as const;

/** Every colour token of one mode of one theme, name (without prefix) to value. */
export function colourTokens(p: Palette, mode: 'dark' | 'light'): Record<string, string> {
  const t: Record<string, string> = {
    page: p.page,
    surface: p.surface,
    text: p.text,
    'text-muted': p.muted,
    'text-inactive': p.inactive,
    border: p.border,
    divider: mix(p.surface, p.border, 0.3),
    primary: p.primary,
    'on-primary': p.onprimary,
    focus: p.primary,
    selection: p.sel,
  };
  t.accent = p.accent ?? p.note;
  t.warm = p.warm ?? p.needs;
  for (const [name, key] of TONES) {
    const tone = p[key];
    // A tint is the tone thinly mixed into the surface; thin enough that the tone still reads as text on it.
    let tint = mix(p.surface, tone, mode === 'dark' ? 0.14 : 0.12);
    for (const k of [0.1, 0.07, 0.05]) {
      if (ratio(tone, tint) >= 4.5) break;
      tint = mix(p.surface, tone, k);
    }
    const on =
      [p.onprimary, '#ffffff', '#000000'].find((c) => ratio(c, tone) >= 4.5) ??
      p.onprimary;
    t[name] = tone;
    t[`${name}-bg`] = tint;
    t[`on-${name}`] = on;
    t[`${name}-tint`] = tint;
    t[`on-${name}-tint`] = tone;
  }
  return t;
}

function rgba(h: string, a: number): string {
  const [r, g, b] = toRgb(h);
  return `rgba(${r}, ${g}, ${b}, ${a})`;
}

/** The effect tokens that follow the primary colour. */
export function effectTokens(
  p: Palette,
  mode: 'dark' | 'light',
  flat = false,
): Record<string, string> {
  if (flat)
    return {
      'glow-focus': `0 0 0 1px ${p.primary}`,
      'scanline-focus': 'none',
      'shadow-2': 'none',
      'shadow-3': 'none',
    };
  return mode === 'dark'
    ? {
        'glow-focus': `0 0 0 1px ${p.primary}, 0 0 8px ${rgba(p.primary, 0.55)}`,
        'scanline-focus': `repeating-linear-gradient(0deg, ${rgba(p.primary, 0.06)} 0 1px, transparent 1px 3px)`,
        'shadow-2': '0 0 0 1px rgba(0, 0, 0, 0.6)',
        'shadow-3': '0 0 0 1px rgba(0, 0, 0, 0.8)',
      }
    : {
        'glow-focus': `0 0 0 1px ${p.primary}`,
        'scanline-focus': 'none',
        'shadow-2': '0 2px 6px rgba(0, 0, 0, 0.12)',
        'shadow-3': '0 8px 24px rgba(0, 0, 0, 0.18)',
      };
}

export function themeDeclarations(
  t: ThemeData,
  mode: 'dark' | 'light',
  indent: string,
): string {
  const p = t[mode];
  const lines: string[] = [];
  for (const [k, v] of Object.entries(colourTokens(p, mode)))
    lines.push(`--ds-color-${k}: ${v};`);
  for (const [k, v] of Object.entries(effectTokens(p, mode, t.flat === true)))
    lines.push(`--ds-${k}: ${v};`);
  t.radius.forEach((r, i) => lines.push(`--ds-radius-${i + 1}: ${r};`));
  return lines.map((l) => `${indent}${l}`).join('\n');
}

const START =
  '/* themes:start (generated by scripts/design/gen-themes.ts; do not edit by hand) */';
const END = '/* themes:end */';

/** The default theme and the six named themes, as the part of tokens.css between the markers. */
export function renderThemeCss(): string {
  const def = THEME_DATA.find((t) => t.id === DEFAULT_THEME) as ThemeData;
  const out: string[] = [START];
  out.push(
    `/* Default: ${def.name}. Dark, then light under the system setting, then light by choice. */`,
  );
  out.push(`:root {\n${themeDeclarations(def, 'dark', '  ')}\n}`);
  out.push(
    `@media (prefers-color-scheme: light) {\n  :root:not([data-theme='dark']) {\n${themeDeclarations(def, 'light', '    ')}\n  }\n}`,
  );
  out.push(`[data-theme='light'] {\n${themeDeclarations(def, 'light', '  ')}\n}`);
  for (const t of THEME_DATA) {
    // The attribute may sit on the page root or on any element (a swatch); a mode on an ancestor still applies.
    const name = `[data-theme-name='${t.id}']`;
    out.push(`/* ${t.name} */\n${name} {\n${themeDeclarations(t, 'dark', '  ')}\n}`);
    out.push(
      `@media (prefers-color-scheme: light) {\n  :root:not([data-theme='dark']) ${name},\n  :root:not([data-theme='dark'])${name} {\n${themeDeclarations(t, 'light', '    ')}\n  }\n}`,
    );
    out.push(
      `[data-theme='light'] ${name},\n[data-theme='light']${name} {\n${themeDeclarations(t, 'light', '  ')}\n}`,
    );
    out.push(
      `[data-theme='dark'] ${name},\n[data-theme='dark']${name} {\n${themeDeclarations(t, 'dark', '  ')}\n}`,
    );
    // A sample of a theme (ThemePreview) sits inside a page in any theme and mode, so it pins its own mode with
    // more weight than the page's rules above: the light and the dark sample both win over the page's mode.
    for (const mode of ['light', 'dark'] as const)
      out.push(
        `:root [data-theme='${mode}']${name} {\n${themeDeclarations(t, mode, '  ')}\n}`,
      );
  }
  out.push(...renderPaletteCss());
  out.push(END);
  return out.join('\n');
}

/**
 * The terminal theme's amber and ice palettes: `data-pal` on the page root (and on a theme preview, which is not the
 * root), after every mode rule so it wins. Each palette has a dark and a light form (CRSP371): dark is the default,
 * light follows the device under the system mode and applies by choice.
 */
export function renderPaletteCss(): string[] {
  const t = THEME_DATA.find((x) => x.id === 'terminal') as ThemeData;
  return (['amber', 'ice'] as const).map((pal) => {
    const base = `[data-theme-name='terminal'][data-pal='${pal}']`;
    const preview = `.ds-theme-preview${base}`;
    const both = { ...t, dark: TERMINAL[pal], light: TERMINAL_LIGHT[pal] };
    const dark = themeDeclarations(both, 'dark', '  ');
    const light = themeDeclarations(both, 'light', '  ');
    const lightIn = themeDeclarations(both, 'light', '    ');
    return [
      `/* Terminal, ${pal} palette: dark, then light under the system setting, then light and dark by choice. */`,
      `:root${base},
${preview}[data-theme='dark'] {
${dark}
}`,
      `@media (prefers-color-scheme: light) {
  :root${base}:not([data-theme='dark']) {
${lightIn}
  }
}`,
      `:root${base}[data-theme='light'],
${preview}[data-theme='light'] {
${light}
}`,
      `:root${base}[data-theme='dark'] {
${dark}
}`,
    ].join('\n');
  });
}

export const MARKERS = { START, END };
