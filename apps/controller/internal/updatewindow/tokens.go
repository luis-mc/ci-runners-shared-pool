package updatewindow

import (
	"bytes"
	"fmt"
	"go/format"
	"regexp"
	"strconv"
	"strings"
)

// tokenFields maps the CSS custom property to the Palette field the generator fills.
var tokenFields = []struct{ CSS, Field string }{
	{"--ds-color-page", "Page"}, {"--ds-color-surface", "Surface"}, {"--ds-color-text", "Text"},
	{"--ds-color-text-muted", "TextMuted"}, {"--ds-color-border", "Border"}, {"--ds-color-divider", "Divider"},
	{"--ds-color-primary", "Primary"}, {"--ds-color-on-primary", "OnPrimary"}, {"--ds-color-focus", "Focus"},
	{"--ds-color-selection", "Selection"}, {"--ds-color-done", "Done"}, {"--ds-color-problem", "Problem"},
	{"--ds-color-needs-you", "NeedsYou"},
}

var customProp = regexp.MustCompile(`(--ds-[a-z0-9-]+)\s*:\s*([^;]+);`)

// ParseTokens reads the default theme (Phosphor, dark) from tokens.css: the first :root block
// after the "themes:start" marker.
func ParseTokens(css string) (Palette, error) {
	i := strings.Index(css, "themes:start")
	if i < 0 {
		return Palette{}, fmt.Errorf("tokens.css has no themes:start marker")
	}
	rest := css[i:]
	open := strings.Index(rest, ":root {")
	if open < 0 {
		return Palette{}, fmt.Errorf("no :root block after themes:start")
	}
	rest = rest[open:]
	end := strings.Index(rest, "}")
	if end < 0 {
		return Palette{}, fmt.Errorf("unterminated :root block")
	}
	vals := map[string]string{}
	for _, m := range customProp.FindAllStringSubmatch(rest[:end], -1) {
		vals[m[1]] = strings.TrimSpace(m[2])
	}
	var p Palette
	dst := map[string]*RGB{
		"Page": &p.Page, "Surface": &p.Surface, "Text": &p.Text, "TextMuted": &p.TextMuted, "Border": &p.Border,
		"Divider": &p.Divider, "Primary": &p.Primary, "OnPrimary": &p.OnPrimary, "Focus": &p.Focus,
		"Selection": &p.Selection, "Done": &p.Done, "Problem": &p.Problem, "NeedsYou": &p.NeedsYou,
	}
	for _, f := range tokenFields {
		c, err := parseHex(vals[f.CSS])
		if err != nil {
			return Palette{}, fmt.Errorf("%s: %w", f.CSS, err)
		}
		*dst[f.Field] = c
	}
	return p, nil
}

func parseHex(s string) (RGB, error) {
	if len(s) != 7 || s[0] != '#' {
		return RGB{}, fmt.Errorf("%q is not a #rrggbb colour", s)
	}
	n, err := strconv.ParseUint(s[1:], 16, 32)
	if err != nil {
		return RGB{}, err
	}
	return RGB{uint8(n >> 16), uint8(n >> 8), uint8(n)}, nil
}

// GoSource is tokens_gen.go for a palette.
func GoSource(p Palette) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/updatewindow/genart from packages/ui/src/tokens.css; DO NOT EDIT.\n\n")
	b.WriteString("package updatewindow\n\n")
	b.WriteString("// Phosphor is the Phosphor dark theme, the console's default (design-system tokens).\nvar Phosphor = Palette{\n")
	src := map[string]RGB{
		"Page": p.Page, "Surface": p.Surface, "Text": p.Text, "TextMuted": p.TextMuted, "Border": p.Border,
		"Divider": p.Divider, "Primary": p.Primary, "OnPrimary": p.OnPrimary, "Focus": p.Focus,
		"Selection": p.Selection, "Done": p.Done, "Problem": p.Problem, "NeedsYou": p.NeedsYou,
	}
	for _, f := range tokenFields {
		c := src[f.Field]
		fmt.Fprintf(&b, "\t%s: RGB{0x%02x, 0x%02x, 0x%02x}, // %s\n", f.Field, c.R, c.G, c.B, f.CSS)
	}
	b.WriteString("}\n")
	if out, err := format.Source(b.Bytes()); err == nil {
		return out
	}
	return b.Bytes()
}
